const assert = require('assert');
const fs = require('fs');
const path = require('path');
const Module = require('module');
let ts;
try { ts = require('typescript'); }
catch { ts = require('/opt/nvm/versions/node/v22.16.0/lib/node_modules/typescript'); }
const root = path.resolve(__dirname, '..');
require.extensions['.ts'] = (loadedModule, filename) => {
  const source = fs.readFileSync(filename, 'utf8');
  const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2021, resolveJsonModule: true, esModuleInterop: true } }).outputText;
  loadedModule._compile(compiled, filename);
};
const scanner = require(path.join(root, 'src/services/documentScannerService.ts'));
assert.equal(scanner.normalizeScannerUri('/data/user/0/app/cache/scan.jpg'), 'file:///data/user/0/app/cache/scan.jpg');
assert.equal(scanner.normalizeScannerUri('file:///tmp/scan.jpg'), 'file:///tmp/scan.jpg');
assert.equal(scanner.normalizeScannerUri('content://media/document/1'), 'content://media/document/1');
assert.equal(scanner.normalizeScannerUri('scan.jpg'), 'file:///scan.jpg');
assert.equal(scanner.hasScannedImages(4), true, 'keep captured pages if a platform returns them with a cancellation status');
assert.equal(scanner.hasScannedImages(0), false);
assert.equal(scanner.MAX_SCAN_WIDTH, 1800);
assert(scanner.SCANNED_IMAGE_QUALITY >= 0.7 && scanner.SCANNED_IMAGE_QUALITY <= 1);
const firstPage = { id: 'page-1', uri: 'file:///first.jpg' };
const secondPage = { id: 'page-2', uri: 'file:///second.jpg' };
const thirdPage = { id: 'page-3', uri: 'file:///third.jpg' };
const generatedIds = [scanner.createScanPageId('document'), scanner.createScanPageId('document')];
assert.notEqual(generatedIds[0], generatedIds[1], 'native scanner pages must use unique page IDs');
const captureBatch = scanner.appendScanPages([firstPage], [secondPage, firstPage, thirdPage]);
assert.deepEqual(captureBatch.map(page => page.id), ['page-1', 'page-2', 'page-3'], 'appending captures must preserve order without duplicating existing IDs');
assert.deepEqual(scanner.removeScanPage(captureBatch, 'page-2').map(page => page.id), ['page-1', 'page-3'], 'deleting one page must retain the order and identity of remaining pages');
assert.deepEqual(scanner.removeScanPage(captureBatch, 'missing'), captureBatch, 'deleting an unknown page must not change the collection');
const src = fs.readFileSync(path.join(root, 'src/services/documentScannerService.ts'), 'utf8');
assert(src.includes("import('react-native-document-scanner-plugin')"), 'native document scanner must be used');
assert(!src.includes('maxNumDocuments:'), 'scanner must not impose a fixed page limit');
const resultEntry = fs.readFileSync(path.join(root, 'src/screens/results/ResultEntryScreen.tsx'), 'utf8');
const reviewScreen = fs.readFileSync(path.join(root, 'src/screens/results/CapturedPagesReviewScreen.tsx'), 'utf8');
const previewScreen = fs.readFileSync(path.join(root, 'src/screens/results/PdfPreviewScreen.tsx'), 'utf8');
const app = fs.readFileSync(path.join(root, 'App.tsx'), 'utf8');
assert(resultEntry.includes('captureDocumentPages()'), 'Scan Answer Copy must open the native camera scanner directly');
assert(!fs.existsSync(path.join(root, 'src/screens/results/ScannerScreen.tsx')), 'the intermediate scanner selection screen must be removed');
assert(!resultEntry.includes("navigate('Scanner'"), 'Scan Answer Copy must not navigate to a scanner selection screen');
assert(resultEntry.includes('appendScanPages(previous'), 'captured pages must append to the existing collection');
assert(resultEntry.includes('navigate(\'CapturedPagesReview\''), 'successful scanning must open captured-page review');
assert(!resultEntry.includes('openPicker') && !app.includes("case 'Scanner'"), 'gallery selection and the old scanner route must be unavailable');
assert(reviewScreen.includes('removeScanPage') && reviewScreen.includes('createAnswerCopyPdf'), 'review must support deletion and generate a PDF from the retained pages');
assert(reviewScreen.includes('captureDocumentPages()') && reviewScreen.includes('appendScanPages(previous'), 'review must allow another native scan without losing existing pages');
assert(!reviewScreen.includes('editCapturedPage') && !reviewScreen.includes('CapturedPageEdit'), 'captured-page editing must not be available in review');
assert(reviewScreen.includes('disabled={generating || capturingMore || !scanPages.length}'), 'review must prevent PDF generation when no pages remain or a new scan is in progress');
const pdfService = fs.readFileSync(path.join(root, 'src/services/pdfService.ts'), 'utf8');
assert(pdfService.includes('for (const page of pages)') && pdfService.includes('base64Pages.join'), 'PDF pages must be processed and emitted in capture order');
assert(previewScreen.includes("t('submitPdf')") && !previewScreen.includes("t('sharePdf')"), 'PDF attachment must remain and the Save PDF Copy action must be removed');
assert(app.includes("case 'CapturedPagesReview'") && !app.includes("case 'CapturedPageEdit'"), 'review route must remain and page editor route must be removed');
assert(!previewScreen.includes("popTo('Scanner')"), 'PDF retry must not navigate to the removed scanner route');
console.log('Scanner checks passed: ordered native capture, direct scanner entry, review/deletion, and PDF attachment.');
